import { BATTERY } from "../config";

export interface TwinState {
  /** State of charge as a fraction in [0, 1]. */
  soc: number;
  /** Polarization voltage in volts. */
  v1: number;
  /** Cell temperature in degrees Celsius. */
  tempC: number;
}

export interface TwinOutput {
  voltageV: number;
  tempC: number;
  state: TwinState;
}

export function clamp(value: number, min: number, max: number): number {
  return Math.min(max, Math.max(min, value));
}

/** Interpolate the configured open-circuit-voltage table at a bounded SOC. */
export function ocvFromSoc(soc: number): number {
  const points = BATTERY.OCV_V;
  const bounded = clamp(soc, 0, 1);
  const position = bounded * (points.length - 1);
  const lower = Math.floor(position);
  if (lower >= points.length - 1) return points[points.length - 1];
  const fraction = position - lower;
  return points[lower] * (1 - fraction) + points[lower + 1] * fraction;
}

/** Invert the open-circuit-voltage table to estimate SOC from a measured cell voltage. */
export function socFromOcv(voltageV: number): number {
  const points = BATTERY.OCV_V;
  if (voltageV <= points[0]) return 0;
  if (voltageV >= points[points.length - 1]) return 1;
  for (let index = 0; index < points.length - 1; index += 1) {
    const low = points[index];
    const high = points[index + 1];
    if (voltageV <= high) {
      const fraction = (voltageV - low) / (high - low);
      return (index + fraction) / (points.length - 1);
    }
  }
  return 1;
}

/**
 * First-order resistor-capacitor battery model.
 *
 * Positive current is charging. Heat is generated by both the ohmic and
 * polarization resistances and lost to ambient through a single thermal
 * resistance.
 */
export class OneRcTwin {
  private state: TwinState;

  constructor(initial?: Partial<TwinState>) {
    this.state = {
      soc: initial?.soc ?? BATTERY.SOC_0,
      v1: initial?.v1 ?? 0,
      tempC: initial?.tempC ?? BATTERY.T_amb_C,
    };
  }

  reset(initial?: Partial<TwinState>): void {
    this.state = {
      soc: initial?.soc ?? BATTERY.SOC_0,
      v1: initial?.v1 ?? 0,
      tempC: initial?.tempC ?? BATTERY.T_amb_C,
    };
  }

  get currentState(): TwinState {
    return { ...this.state };
  }

  setState(state: Partial<TwinState>): void {
    this.state = { ...this.state, ...state };
  }

  /** Advance the model by the configured time step. */
  step(currentA: number, ambientC: number = BATTERY.T_amb_C, dt_s: number = 1): TwinOutput {
    const decay = Math.exp(-dt_s / BATTERY.tau1_s);
    const soc = this.state.soc + (BATTERY.eta * currentA * dt_s) / (3600 * BATTERY.Q_Ah);
    const v1 = this.state.v1 * decay + BATTERY.R1_ohm * (1 - decay) * currentA;
    const heatW = currentA * currentA * (BATTERY.R0_ohm + BATTERY.R1_ohm);
    const tempC =
      this.state.tempC +
      (dt_s / BATTERY.C_th_J_per_K) *
        (heatW - (this.state.tempC - ambientC) / BATTERY.R_th_K_per_W);

    this.state = { soc: clamp(soc, 0, 1), v1, tempC };
    const voltageV = ocvFromSoc(this.state.soc) + currentA * BATTERY.R0_ohm + this.state.v1;
    return { voltageV, tempC: this.state.tempC, state: this.currentState };
  }
}
